#!/usr/bin/env python3
"""Generate exact finite Lorentz tensor certificates, checked by Lean.

Only rational Gaussian elimination and the standard library are used. Output
is proof source, not a trusted rank premise. Run from the repository root.
"""
from fractions import Fraction as Q
from itertools import product
from pathlib import Path
from math import prod
import re

Z = [1, -1, -1, 1]
X = [1, 1, -1, -1]
REAL = [[Q(3, 2), -1, 0, Q(-1, 2)], [-1, 1, 0, 1],
        [0, 0, 1, 0], [Q(1, 2), -1, 0, Q(1, 2)]]
IMAG = [[Q(3, 2), 0, 1, Q(-1, 2)], [0, 1, 0, 0],
        [1, 0, 1, -1], [Q(1, 2), 0, 1, Q(1, 2)]]


def allowed(t):
    return prod(Z[i] for i in t) == 1 and prod(X[i] for i in t) == 1


def canonical(t):
    i, j, k, l = t
    return min(i, j), max(i, j), k, l


def add(row, key, value):
    row[key] = row.get(key, Q(0)) + value
    if not row[key]:
        del row[key]


def name(t):
    return ''.join(map(str, t))


def comp(t):
    return 'component b ' + ' '.join(map(str, t))


def scalar(q):
    q = Q(q)
    return f'({q.numerator}/{q.denominator} : ℂ)'


def expression(row):
    return ' + '.join(f'{scalar(v)}*{comp(t)}' for t, v in sorted(row.items())) or '0'


def certificates():
    variables = sorted({canonical(t) for t in product(range(4), repeat=4) if allowed(t)})
    free = [(0, 0, 1, 1), (0, 1, 0, 1)]
    order = [t for t in variables if t not in free] + free
    raw = []
    for label, matrix in [('real', REAL), ('imag', IMAG)]:
        for t in product(range(4), repeat=4):
            if t != canonical(t):
                continue
            row = {}
            for u in product(range(4), repeat=4):
                if allowed(u):
                    add(row, canonical(u), prod(Q(matrix[i][j]) for i, j in zip(t, u)))
            if allowed(t):
                add(row, canonical(t), -1)
            if row:
                raw.append((label, t, row))
    raw.sort(key=lambda r: (len(r[2]), r[0], r[1]))
    pivots, records = {}, []
    for label, t, initial in raw:
        row, uses = dict(initial), []
        while row:
            p = next(k for k in order if k in row)
            if p not in pivots:
                factor = row[p]
                row = {k: v/factor for k, v in row.items()}
                pivots[p] = len(records)
                records.append((p, label, t, initial, uses, factor, row))
                break
            index = pivots[p]
            v = row[p]
            uses.append((index, v))
            for k, w in records[index][-1].items():
                add(row, k, -v*w)
    assert len(variables) == 40 and len(records) == 38
    assert not any(t in pivots for t in free)
    return records, variables


def generate():
    records, variables = certificates()
    out = ['/-! The following sparse certificates are generated by the repository\n'
           'script and rechecked by Lean using actual group equations. -/', '']
    for n, (p, label, t, initial, uses, factor, row) in enumerate(records):
        out += ['include h hs in', f'theorem row{n} : {expression(row)} = 0 := by',
                f'  have he := h (shear {"1" if label == "real" else "Complex.I"}) ' + ' '.join(f'(E {i})' for i in t),
                f'  simp only [{label}_basis,map_sum,LinearMap.sum_apply,map_smul,',
                '    LinearMap.smul_apply,smul_eq_mul] at he',
                f'  norm_num [Fin.sum_univ_succ,{label}Rows] at he',
                '  simp only [← component_apply] at he',
                '  simp only [normalize b h hs] at he',
                '  norm_num [normalComponent,killed,signsZ,signsX,← component_apply] at he',
                '  linear_combination ' + scalar(1/factor) + '*he' + ''.join(
                    f' - {scalar(v/factor)}*(row{i} b h hs)' for i, v in uses), '']
    # Back substitution: each component is expressed in the two fixed coordinates.
    values = {t: {t: Q(1)} for t in [(0, 0, 1, 1), (0, 1, 0, 1)]}
    for n in sorted(range(len(records)), key=lambda n: records[n][0], reverse=True):
        p, _, _, _, _, _, row = records[n]
        val = {}
        for k, v in row.items():
            if k != p:
                for t, w in values[k].items():
                    add(val, t, -v*w)
        values[p] = val
        out += ['include h hs in', f'theorem value{name(p)} : {comp(p)} = {expression(val)} := by',
                f'  have he := row{n} b h hs']
        deps = [k for k in row if k != p and k not in [(0, 0, 1, 1), (0, 1, 0, 1)]]
        if deps:
            out += ['  rw [' + ','.join(f'value{name(k)} b h hs' for k in deps) + '] at he']
        out += ['  linear_combination he', '']
    out += ['def metric (i j : Fin 4) : ℂ := if i = j then (![1,-1,-1,-1] : Fin 4 → ℂ) i else 0', '']
    formula = ('-component b 0 0 1 1*(metric i j*metric k l) - '
               'component b 0 1 0 1*(metric i k*metric j l+metric i l*metric j k)')
    for i, j in product(range(4), repeat=2):
        rhs = re.sub(r'\bi\b', str(i), formula)
        rhs = re.sub(r'\bj\b', str(j), rhs)
        out += ['include h hs in', f'theorem components{i}{j} (k l : Fin 4) :',
                f'    component b {i} {j} k l = {rhs} := by',
                '  fin_cases k <;> fin_cases l',
                '  all_goals rw [normalize b h hs]',
                '  all_goals norm_num [normalComponent,killed,signsZ,signsX,metric,← component_apply,',
                '    ' + ','.join(f'value{name(t)} b h hs' for t in sorted(values) if t not in [(0, 0, 1, 1), (0, 1, 0, 1)]) + ']']
        if i == j:
            out.append('  all_goals ring')
        out.append('')
    out += ['include h hs in', 'theorem components (i j k l : Fin 4) :',
            f'    component b i j k l = {formula} := by',
            '  fin_cases i <;> fin_cases j']
    for i, j in product(range(4), repeat=2):
        out.append(f'  · exact components{i}{j} b h hs k l')
    out.append('')
    return '\n'.join(out)


if __name__ == '__main__':
    path = Path('Physics/FieldTheory/Jets/Lorentz/LorentzRankFour.lean')
    directory = Path('Physics/FieldTheory/Jets/LorentzRankFour/Core')
    directory.mkdir(exist_ok=True)
    basic = directory / 'Basic.lean'
    if not basic.exists():
        prefix = path.read_text().split('/-! The following sparse certificates')[0]
        basic.write_text(prefix.rstrip() + '\n\nend\nend Physics.LorentzRankFour\n')
    generated = generate()
    values_start = generated.index('include h hs in\ntheorem value')
    metric_start = generated.index('def metric')
    comps_start = generated.index('include h hs in\ntheorem components00')
    final_start = generated.index('include h hs in\ntheorem components (')
    rows = re.findall(r'include h hs in\ntheorem row\d+.*?(?=include h hs in\ntheorem row|\Z)',
                      generated[:values_start], re.S)
    comps = re.findall(r'include h hs in\ntheorem components\d\d.*?(?=include h hs in\ntheorem components|\Z)',
                       generated[comps_start:final_start], re.S)
    assert len(rows) == 38 and len(comps) == 16
    header = ('\n/-! Generated exact certificates; see generate-rank-four-control.py.\n'
              'Each identity is rechecked by Lean, without imported rank premises. -/\n'
              'namespace Physics.LorentzRankFour\nset_option autoImplicit false\n'
              'noncomputable section\nopen Math LorentzFiniteControls LorentzDirections\n'
              'variable (b : Tensor)\n'
              '  (h : ∀ g u v w x, b (direction g u) (direction g v)\n'
              '    (direction g w) (direction g x) = b u v w x)\n'
              '  (hs : ∀ u v w x, b u v w x = b v u w x)\n\n')
    previous = 'Basic'
    def write_module(label, text):
        global previous
        (directory / (label + '.lean')).write_text(
            'import Physics.FieldTheory.Jets.LorentzRankFour.Core.' + previous + '\n' +
            header + text.strip() + '\n\nend\nend Physics.LorentzRankFour\n')
        previous = label
    for start in range(0, 38, 8):
        write_module('Rows' + str(start // 8), '\n'.join(rows[start:start+8]))
    write_module('Values', generated[values_start:metric_start])
    for start in range(0, 16, 4):
        write_module('Components' + str(start // 4),
                     (generated[metric_start:comps_start] if start == 0 else '') + '\n'.join(comps[start:start+4]))
    path.write_text('import Physics.FieldTheory.Jets.LorentzRankFour.Core.Components3\n' +
                    header + generated[final_start:].strip() + '\n\nend\nend Physics.LorentzRankFour\n')
    print('Generated 38 sparse row proofs and 38 component reconstructions; all require Lean checking.')
