#!/usr/bin/env python3
"""Emit untrusted integer witnesses for SparseMatrixCertificate to check in Lean.

The output contains data only. No proof term or axiom is generated by Python.
"""

import argparse
from fractions import Fraction
import json
from math import lcm

from lie_certificate import Span, check, lie_candidate, sparse_matrix, validate_input


def integer(value):
    value = Fraction(value)
    check(value.denominator == 1, "nonintegral certificate coefficient")
    return str(value.numerator) if value >= 0 else f"({value.numerator})"


def code(matrix):
    return "[" + ", ".join(f"(({i}, {j}), {integer(v)})"
                           for (i, j), v in sorted(matrix.items())) + "]"


def vector(values):
    return "![\n  " + ",\n  ".join(values) + "]"


def family(data, nodes, dimension, root_count, prefix):
    candidate = lie_candidate(data, nodes, dimension, root_count)
    basis = [{(i, j): Fraction(v) for i, j, v in row["entries"]}
             for row in candidate["basis"]]
    generators = [sparse_matrix(data[kind][node]) for kind, node in candidate["generators"]]
    generator_count = len(generators)
    origins = []
    for index, row in enumerate(candidate["basis"]):
        origin = row["provenance"]
        if "seed" in origin:
            kind, node = origin["seed"]
            j = nodes.index(node)
            if kind == "diagonal":
                # H_j = [E_j,F_j]; F_j has already been inserted into the basis.
                origins.append(f"Sum.inr ({j}, {len(nodes) + j})")
                check(len(nodes) + j < index, "non-well-founded Cartan provenance")
            else:
                g = candidate["generators"].index([kind, node])
                origins.append(f"Sum.inl {g}")
        else:
            g, parent = origin["bracket"]
            check(parent < index, "non-well-founded bracket provenance")
            origins.append(f"Sum.inr ({g}, {parent})")

    span = Span()
    for index, matrix in enumerate(basis):
        span.insert(matrix, {"basis": index})
    check(len(span.basis) == dimension, "dependent basis")
    extracts = [(p, span.reduce({p: 1})[1]) for p in sorted(span.pivots)]
    duals, scales = [], []
    for i in range(dimension):
        functional = {p: coords[i] for p, coords in extracts if coords.get(i, 0)}
        scale = lcm(*(v.denominator for v in functional.values()))
        functional = {p: v * scale for p, v in functional.items()}
        for j, matrix in enumerate(basis):
            check(sum(v * matrix.get(p, 0) for p, v in functional.items()) ==
                  (scale if i == j else 0), "bad dual functional")
        duals.append(code(functional))
        scales.append(str(scale))

    closure = [["[]"] * dimension for _ in generators]
    for g, b, coeffs in candidate["generator_closure"]:
        closure[g][b] = "[" + ", ".join(f"({j}, {integer(c)})" for j, c in coeffs) + "]"

    declarations = [
        ("Basis", f"Fin {dimension} → Code (Fin 27)", vector([code(m) for m in basis])),
        ("Generators", f"Fin {generator_count} → Code (Fin 27)", vector([code(m) for m in generators])),
        ("Origin", f"Fin {dimension} → Fin {generator_count} ⊕ (Fin {generator_count} × Fin {dimension})",
         vector(origins)),
        ("Closure", f"Fin {generator_count} → Fin {dimension} → List (Fin {dimension} × ℤ)",
         vector([vector(row) for row in closure])),
        ("Dual", f"Fin {dimension} → Code (Fin 27)", vector(duals)),
        ("Scale", f"Fin {dimension} → ℤ", vector(scales)),
    ]
    return "\n\n".join(f"def {prefix}{name} : {ty} :=\n{value}"
                         for name, ty, value in declarations)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", help="JSON emitted by ExportMatrices.lean")
    args = parser.parse_args()
    with open(args.input, encoding="utf-8") as handle:
        data = json.load(handle)
    validate_input(data)
    print("import Math.LieAlgebras.SparseMatrixCertificate\n")
    print("/-! Untrusted generated data, checked by LieCertificateChecks.\n"
          "Regenerate with tools/e6/export_lean_certificate.py; no generated proofs. -/\n")
    print("set_option autoImplicit false\nset_option maxRecDepth 4096\n")
    print("namespace GUT.E6.Minuscule.LieData\n\nopen GUT.SparseMatrixCertificate\n")
    print(family(data, list(range(6)), 78, 72, "e6"))
    print()
    print(family(data, data["d5_nodes"], 45, 40, "d5"))
    print("\nend GUT.E6.Minuscule.LieData")


if __name__ == "__main__":
    main()
