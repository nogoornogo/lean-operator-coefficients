#!/usr/bin/env python3
"""Generate Lean-checkable rank factorizations from exact rational JSON matrices.

Input: a list of objects with rows, cols, entries (integers or fraction strings).
Output: Lean source on stdout. Python arithmetic is not a proof premise.
"""
import argparse
import json
from fractions import Fraction
from pathlib import Path


def identity(n):
    return [[Fraction(i == j) for j in range(n)] for i in range(n)]


def product(a, b, width):
    return [[sum((x * b[k][j] for k, x in enumerate(row)), Fraction(0))
             for j in range(width)] for row in a]


def certificate(item):
    m, n = item["rows"], item["cols"]
    if type(m) is not int or type(n) is not int or min(m, n) < 0:
        raise ValueError("rows and cols must be nonnegative integers")
    entries = item["entries"]
    if len(entries) != m or any(len(row) != n for row in entries):
        raise ValueError("matrix dimensions do not match entries")
    if any(type(x) not in (int, str) for row in entries for x in row):
        raise ValueError("use exact integers or fraction strings, not floating point")
    a = [[Fraction(x) for x in row] for row in entries]
    reduced, transform, pivots = [row[:] for row in a], identity(m), []
    for j in range(n):
        k = len(pivots)
        pivot = next((i for i in range(k, m) if reduced[i][j]), None)
        if pivot is None:
            continue
        for mat in (reduced, transform):
            mat[k], mat[pivot] = mat[pivot], mat[k]
        scale = reduced[k][j]
        reduced[k] = [x / scale for x in reduced[k]]
        transform[k] = [x / scale for x in transform[k]]
        for i in range(m):
            if i != k:
                scale = reduced[i][j]
                reduced[i] = [x - scale * y for x, y in zip(reduced[i], reduced[k])]
                transform[i] = [x - scale * y for x, y in zip(transform[i], transform[k])]
        pivots.append(j)
    r = len(pivots)
    b = [[row[j] for j in pivots] for row in a]
    c, left = reduced[:r], transform[:r]
    right = [[Fraction(i == j) for j in pivots] for i in range(n)]
    assert product(b, c, n) == a
    assert product(left, b, r) == identity(r)
    assert product(c, right, r) == identity(r)
    return a, b, c, left, right, r


def lean_matrix(mat, rows, cols):
    if rows == 0 or cols == 0:
        return "fun _ _ => 0"
    def scalar(x):
        return str(x.numerator) if x.denominator == 1 else f"({x.numerator} / {x.denominator})"
    return "!![" + "; ".join(", ".join(scalar(x) for x in row) for row in mat) + "]"


def generate(items):
    lines = ["import Math.LinearAlgebra.ExactRankCertificate", "",
             "/-! Generated by tools/exact-rank/certify.py; identities checked by the Lean kernel. -/",
             "namespace Math.ExactRankExamples", "open ExactRankCertificate", ""]
    for i, item in enumerate(items):
        a, b, c, left, right, r = certificate(item)
        m, n = item["rows"], item["cols"]
        lines += [f"def matrix{i} : Matrix (Fin {m}) (Fin {n}) ℚ := {lean_matrix(a, m, n)}",
                  f"def certificate{i} : Certificate (T := Fin {r}) matrix{i} where",
                  f"  columns := {lean_matrix(b, m, r)}",
                  f"  rows := {lean_matrix(c, r, n)}",
                  f"  left := {lean_matrix(left, r, m)}",
                  f"  right := {lean_matrix(right, n, r)}",
                  "  factor := by decide +kernel", "  left_inverse := by decide +kernel",
                  "  right_inverse := by decide +kernel",
                  f"theorem rank{i} : (matrix{i}.map (Rat.castHom ℂ)).rank = {r} :=",
                  f"  mapped_rank certificate{i} (Rat.castHom ℂ)", ""]
    return "\n".join(lines + ["end Math.ExactRankExamples", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path)
    parser.add_argument("--check", type=Path, help="check committed generated source")
    args = parser.parse_args()
    result = generate(json.loads(args.input.read_text()))
    if args.check:
        if result != args.check.read_text():
            raise SystemExit("generated Lean source differs")
        print("Exact certificate regeneration matched")
    else:
        print(result, end="")


if __name__ == "__main__":
    main()
